// Builds the one theme asset, assets/xavia-fit-finder.js, from the sources in this folder:
// the engine (size math), the texts, the dialog and the CSS. The theme loads it only when a shopper needs it.
//   node integrations/shopify/impact/fit-finder/build.mjs      → writes dist/xavia-fit-finder.js (git-ignored)
// Build right before uploading to the theme, so the asset always matches the sources.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const here = new URL('.', import.meta.url)
const read = name => readFileSync(new URL(name, here), 'utf8')
const IMPORT = /^import \{[^}]*\} from '\.\/xavia-fit-(engine|i18n|body|viewer)\.js';\n/gm
const DECLARED = /^(?:export )?(?:const|let|function\*?|class) (\w+)/gm

export function buildAsset() {
  const parts = ['xavia-fit-engine.js', 'xavia-fit-i18n.js', 'xavia-fit-body.js', 'xavia-fit-viewer.js', 'xavia-fit-finder.js'].map(file => [file, read(file)])
  // One module scope: two top-level declarations with one name would break the asset.
  const seen = new Map()
  for (const [file, source] of parts) for (const [, name] of source.matchAll(DECLARED)) {
    if (seen.has(name)) throw new Error(`${name} is declared in ${seen.get(name)} and ${file}`)
    seen.set(name, file)
  }
  const css = read('xavia-fit-finder.css')
  const ui = parts.at(-1)[1].replace(IMPORT, '')
  if (!ui.includes("'__XFF_CSS__'")) throw new Error('xavia-fit-finder.js lost its CSS placeholder')
  return [
    '// GENERATED by integrations/shopify/impact/fit-finder/build.mjs: edit the sources there, not this file.',
    ...parts.slice(0, -1).map(([file, source]) => `// ---- ${file}\n${source.replace(IMPORT, '')}`),
    `// ---- xavia-fit-finder.js\n${ui.replace("'__XFF_CSS__'", () => JSON.stringify(css))}`,
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(new URL('dist/', here), { recursive: true })
  writeFileSync(new URL('dist/xavia-fit-finder.js', here), buildAsset())
  console.log('wrote dist/xavia-fit-finder.js')
}
