// Drives the stand-in page (server.mjs) in Chromium: every shopper path of the fit finder, with checks and screenshots.
//   PLAYWRIGHT=/path/to/playwright node integrations/shopify/impact/verification/fit-finder/run.mjs <base url> <screenshot dir>
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'

const { chromium } = await import(process.env.PLAYWRIGHT || 'playwright')
const base = process.argv[2] || 'http://127.0.0.1:4317/'
const shots = process.argv[3] || 'fit-finder-shots'
mkdirSync(shots, { recursive: true })
const browser = await chromium.launch()
const results = []
async function scenario(name, viewport, fn) {
  const context = await browser.newContext({ viewport, locale: 'en-GB' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  try {
    await fn(page)
    assert.deepEqual(errors, [], 'no page errors')
    results.push(['pass', name])
  } catch (error) {
    results.push(['FAIL', name, error.message.split('\n')[0]])
    await page.screenshot({ path: `${shots}/FAIL-${name.replace(/\W+/g, '-')}.png` }).catch(() => {})
  }
  await context.close()
}
const dialog = page => page.locator('dialog.xff-dialog')
async function fillBasics(page, { height = '178', weight = '80', age = '35' } = {}) {
  await page.locator('#xff-height').fill(height)
  await page.locator('#xff-weight').fill(weight)
  await page.locator('#xff-age').fill(age)
}

