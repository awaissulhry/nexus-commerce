// Drives the stand-in page (server.mjs) in Chromium: every shopper path of the size guide, with checks and screenshots.
//   PLAYWRIGHT=/path/to/playwright node integrations/shopify/impact/verification/fit-finder/run.mjs <base url> <screenshot dir>
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'

const { chromium } = await import(process.env.PLAYWRIGHT || 'playwright')
const base = process.argv[2] || 'http://127.0.0.1:4317/'
const shots = process.argv[3] || 'fit-finder-shots'
mkdirSync(shots, { recursive: true })
// SwiftShader gives headless Chromium a software WebGL, so the 3D body really renders.
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const flatBrowser = await chromium.launch({ args: ['--disable-3d-apis'] })
const results = []
async function scenario(name, viewport, fn, { flat = false } = {}) {
  const context = await (flat ? flatBrowser : browser).newContext({ viewport, locale: 'en-GB' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error' && !/GPU stall/.test(m.text())) errors.push(m.text()) })
  try {
    await fn(page)
    assert.deepEqual(errors, [], 'no page errors')
    results.push(['pass', name])
  } catch (error) {
    results.push(['FAIL', name, error.message.split('\n')[0]])
    await page.screenshot({ path: `${shots}/FAIL-${name.replace(/\W+/g, '-')}.png` }).catch(() => {})
  }
  await context.close()
}
const DESKTOP = { width: 1512, height: 793 }, PHONE = { width: 390, height: 844 }
const dialog = page => page.locator('dialog.xff-dialog')
const screen = page => dialog(page).getAttribute('data-screen')
// Text that only shows when code puts a list or an empty value on the screen.
const noJunk = async page => assert.doesNotMatch(await dialog(page).innerText(), /\bnull\b|undefined|NaN|\[object /, 'no code words on the screen')
// The body glides to its new shape and frame (about half a second); the ring labels come after that.
const settle = async page => { await page.waitForFunction(() => document.querySelectorAll('.xff-3d-label').length > 0, null, { timeout: 5000 }).catch(() => {}); await page.waitForTimeout(500) }
async function openGuide(page, query = 'locale=en') {
  await page.goto(`${base}?${query}`)
  await page.locator('[data-xff-open]').click()
  await dialog(page).waitFor()
}
async function toResult(page, { sex = 'male', height = '178', weight = '80', age = '35', phone = false } = {}) {
  await page.locator('#xff-find').click()
  await page.locator(`#xff-sex-${sex}`).click()
  if (phone) await page.locator('#xff-next').click()
  await page.locator('#xff-height').fill(height)
  await page.locator('#xff-weight').fill(weight)
  if (age) await page.locator('#xff-age').fill(age)
  await page.locator('#xff-next').click()
  assert.equal(await screen(page), 'shape')
  await page.locator('#xff-next').click()
  assert.equal(await screen(page), 'result')
}

