import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { lockSetConfigSql, policySql, runtimeRoleSql } from '@nexus/db-kit/policy-sql'
import type { PlatformTable, PolicyInputs } from './ownership'
import { PLATFORM_ROLE, RUNTIME_LOGIN, RUNTIME_ROLES } from './roles'

/**
 * The policy migration: every grant, policy and role the factory database needs, generated from `ownership/*.json` and
 * the Prisma schema, and checked in as a migration (`npm run policies -w @nexus/factory-db -- <folder>`). Deterministic:
 * the same inputs give the same bytes, so `scripts/factory/check-policy-parity.mjs` can compare the newest policy
 * migration with a fresh run.
 *
 * Each policy migration holds the WHOLE generated SQL, not a delta. It is idempotent and convergent (db-kit's
 * generator drops every policy of a managed table and revokes before it grants), so applying the newest one brings the
 * database to the current classification, also for columns added since (column grants list the columns by name).
 *
 * In order:
 *   1. the runtime roles (NOLOGIN, no administrative attribute);
 *   2. the runtime login `factory_app`: LOGIN without a password (Railway's is set once by hand), no administrative
 *      attribute, a member of every runtime role WITH INHERIT FALSE, SET TRUE (a query that skips the adapter reads
 *      nothing), and never WITH ADMIN OPTION;
 *   3. `set_config` only for the login, so SQL running as a runtime role cannot change its own scope;
 *   4. db-kit's policySql for every walled table: ENABLE and FORCE row-level security, a policy per role and command on
 *      the tenant wall (and site, party), table or column grants;
 *   5. the platform role's grants and policies, which see every row (it has no tenant), on the platform tables only.
 */

export const POLICY_MIGRATION_HEADER =
  '-- @generated by `npm run policies -w @nexus/factory-db -- <folder>` from ownership/*.json and prisma/schema/*.prisma.\n' +
  '-- Never hand-edit: scripts/factory/check-policy-parity.mjs compares the newest policy migration with the generator.\n'

const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]{0,62}$/
const quote = (name: string): string => {
  if (!IDENTIFIER.test(name)) throw new Error(`Invalid identifier: ${JSON.stringify(name)}.`)
  return `"${name}"`
}

/** Step 2: the runtime login and its memberships. Writes to the shared catalogs only when something is missing. */
export function runtimeLoginSql(login: string, roles: readonly string[]): string {
  const q = quote(login)
  const lines = [
    'DO $$ BEGIN',
    `  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${login}') THEN`,
    `    CREATE ROLE ${q} LOGIN NOINHERIT NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION;`,
    '  END IF;',
    `  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${login}' AND (rolsuper OR rolbypassrls OR rolcreatedb OR rolcreaterole OR rolreplication)) THEN`,
    `    RAISE EXCEPTION 'Runtime login ${login} must hold no administrative attribute';`,
    '  END IF;',
  ]
  for (const role of [...roles].sort()) {
    lines.push(
      `  IF NOT EXISTS (SELECT 1 FROM pg_auth_members m WHERE m.roleid = '${role}'::regrole AND m.member = '${login}'::regrole AND m.set_option AND NOT m.inherit_option) THEN`,
      `    GRANT ${quote(role)} TO ${q} WITH INHERIT FALSE, SET TRUE;`,
      '  END IF;',
    )
  }
  lines.push(
    `  IF EXISTS (SELECT 1 FROM pg_auth_members m WHERE m.member = '${login}'::regrole AND (m.inherit_option OR m.admin_option)) THEN`,
    `    RAISE EXCEPTION 'Runtime login ${login} must not inherit or administer a role: grant its roles WITH INHERIT FALSE, SET TRUE';`,
    '  END IF;',
    'END $$;',
  )
  return `${lines.join('\n')}\n`
}

/** Step 5: the platform role sees every row of a platform table. A table no runtime role shares gets its RLS here. */
export function platformPolicySql(tables: readonly PlatformTable[], withSchemaUsage: boolean): string {
  const out: string[] = []
  if (withSchemaUsage && tables.length > 0) out.push(`GRANT USAGE ON SCHEMA "public" TO ${quote(PLATFORM_ROLE)};`)
  const role = quote(PLATFORM_ROLE)
  for (const table of tables) {
    const name = `"public".${quote(table.table)}`
    out.push(`-- ${name}: ${PLATFORM_ROLE}`)
    if (!table.walled) {
      out.push(
        `ALTER TABLE ${name} ENABLE ROW LEVEL SECURITY;`,
        `ALTER TABLE ${name} FORCE ROW LEVEL SECURITY;`,
        `DO $$ DECLARE existing record; BEGIN FOR existing IN SELECT policyname FROM pg_policies WHERE schemaname = 'public' AND tablename = '${table.table}' LOOP EXECUTE format('DROP POLICY %I ON %I.%I', existing.policyname, 'public', '${table.table}'); END LOOP; END $$;`,
        `REVOKE ALL ON TABLE ${name} FROM PUBLIC, ${[...RUNTIME_ROLES].sort().map(quote).join(', ')};`,
      )
    }
    const privileges = (['select', 'insert', 'update', 'delete'] as const).filter((p) => table.privileges.includes(p))
    out.push(`GRANT ${privileges.map((p) => p.toUpperCase()).join(', ')} ON TABLE ${name} TO ${role};`)
    for (const privilege of privileges) {
      const head = `CREATE POLICY ${quote(`${PLATFORM_ROLE}_${privilege}`)} ON ${name} AS PERMISSIVE FOR ${privilege.toUpperCase()} TO ${role}`
      if (privilege === 'insert') out.push(`${head} WITH CHECK (true);`)
      else if (privilege === 'update') out.push(`${head} USING (true) WITH CHECK (true);`)
      else out.push(`${head} USING (true);`)
    }
  }
  return out.length > 0 ? `${out.join('\n')}\n` : ''
}

/** The whole policy migration for these inputs. */
export function policyMigrationSql(inputs: PolicyInputs): string {
  const walled = policySql(inputs.model)
  return [
    POLICY_MIGRATION_HEADER,
    '\n-- 1. Runtime roles\n',
    runtimeRoleSql(RUNTIME_ROLES),
    '\n-- 2. The runtime login\n',
    runtimeLoginSql(RUNTIME_LOGIN, RUNTIME_ROLES),
    '\n-- 3. set_config only for the login\n',
    lockSetConfigSql([RUNTIME_LOGIN], RUNTIME_ROLES),
    '\n-- 4. Walled tables\n',
    walled,
    '\n-- 5. Platform tables\n',
    platformPolicySql(inputs.platformTables, inputs.model.tables.length === 0),
  ].join('')
}

export interface Migration {
  readonly folder: string
  readonly sql: string
}

/** Every migration folder with a migration.sql, in the order Prisma applies them. */
export function readMigrations(dir: string): Migration[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(dir, entry.name, 'migration.sql')))
    .map((entry) => entry.name)
    .sort()
    .map((folder) => ({ folder, sql: readFileSync(join(dir, folder, 'migration.sql'), 'utf8') }))
}

export const isPolicyMigration = (migration: Migration): boolean => migration.sql.startsWith(POLICY_MIGRATION_HEADER)

/**
 * Policy parity: the newest policy migration is the newest migration of all (a schema migration after it would leave
 * its tables or columns without grants and policies), and its SQL is exactly what the generator writes now.
 */
export function checkPolicyParity(migrations: readonly Migration[], expected: string): string[] {
  const policies = migrations.filter(isPolicyMigration)
  const newest = policies.at(-1)
  if (!newest) return ['no policy migration: run `npm run policies -w @nexus/factory-db -- <timestamp>__<module>_policies`']
  const last = migrations.at(-1) as Migration
  const problems: string[] = []
  if (last.folder !== newest.folder) {
    problems.push(`migration ${last.folder} comes after the newest policy migration ${newest.folder}: generate a new policy migration after it`)
  }
  if (newest.sql !== expected) {
    const actual = newest.sql.split('\n')
    const wanted = expected.split('\n')
    const line = wanted.findIndex((text, index) => actual[index] !== text)
    const at = line === -1 ? wanted.length : line
    problems.push(
      `${newest.folder}/migration.sql differs from the generator at line ${at + 1}: ` +
        `found ${JSON.stringify(actual[at] ?? '<end of file>')}, expected ${JSON.stringify(wanted[at] ?? '<end of file>')}; ` +
        're-run `npm run policies -w @nexus/factory-db -- ' + newest.folder + '`',
    )
  }
  return problems
}
