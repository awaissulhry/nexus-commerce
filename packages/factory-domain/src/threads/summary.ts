/** A state code in words; one the map does not know, its code in plain letters ("SOME_STATE" → "Some state"). */
export function stateWordsOf(code: string): Words {
  if (Object.hasOwn(STATE_WORDS, code)) return STATE_WORDS[code]!
  const plain = code.toLowerCase().replace(/_/g, ' ')
  const said = plain.charAt(0).toUpperCase() + plain.slice(1)
  return { it: said, en: said }
}
