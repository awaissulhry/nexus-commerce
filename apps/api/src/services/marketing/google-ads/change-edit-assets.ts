/**
 * Google Ads changes (2026-10-15, programme 2 group G3) — sitelinks, callouts and structured snippets changed where they
 * are. Two ways, one request each:
 *
 *   edit in place       the asset itself changes (sitelink link text, description lines, final URL; callout text; snippet
 *                       header and values): it keeps its id and its numbers, and it changes EVERYWHERE it is linked
 *                       (campaigns, ad groups, the account) — the preview names each place.
 *   replace in ONE campaign (onlyInCampaignId)  a new asset with the edited text is made and linked to that campaign with
 *                       the old link's status, and the old one is unlinked there; the old asset keeps its numbers and stays
 *                       wherever else it is linked. The new asset copies the old one's final mobile URLs and its tracking
 *                       (tracking_url_template, final_url_suffix, url_custom_parameters). This is also the way for an asset Google made (automatically created):
 *                       Google does not let it be changed.
 *
 * Checked 2026-10-15 in Google's v25 reference and guides (curl of developers.google.com/google-ads/api/…):
 *   reference/rpc/v25/AssetOperation  create, update ("customers/{customer_id}/assets/{asset_id}"), update_mask.
 *   reference/rpc/v25/Asset           sitelink_asset, callout_asset, structured_snippet_asset are NOT marked Immutable
 *                                     (text_asset, youtube_video_asset, … are); final_urls, final_mobile_urls mutable;
 *                                     source (AssetSource ADVERTISER / AUTOMATICALLY_CREATED) output only.
 *   reference/rpc/v25/SitelinkAsset   link_text 1–25; description1 / description2 1–35, each "must also be set" with the
 *                                     other. CalloutAsset callout_text 1–25. StructuredSnippetAsset header (Google's list),
 *                                     values 3–10, each 1–25 (change-assets.ts holds the lists and limits).
 *   docs/assets/overview              the table "Asset types linked to customers, campaigns, and ad groups": Callout,
 *                                     Structured snippet and Sitelink are "Mutable: Yes"; "Assets generated by text
 *                                     customization (formerly automatically created assets) cannot be modified."
 * Update masks are snake_case paths (`sitelink_asset.link_text`, `final_urls`); a masked field left out of the body is
 * cleared (PLAN.md "v25 facts"): that is how description lines are taken away.
 *
 * Money: an asset raises no bid and no budget (no SPENDS MONEY).
 */
import { changeLines, plural, type GoogleChangeDraft } from './change-draft.js'
import { httpsUrlProblem, tagWarning, textKey, widthProblem } from './change-ads.js'
import { ASSET_FIELD_TYPES, ASSET_LIMITS, SNIPPET_LANGUAGES, snippetHeader, snippetHeaders, type AssetFieldType, type AssetLinkStatus } from './change-assets.js'
import type { LiveAssetLink, LiveEditAsset } from './live-edit.js'
import type { GoogleMutateOperation, GoogleMutateResponse } from './write-client.js'

export interface AssetEdit {
  assetId: string
  linkText?: string
  /** null = no description lines (both go). */
  description1?: string | null
  description2?: string | null
  finalUrl?: string
  calloutText?: string
  header?: string
  /** The language of the header (as set-google-assets takes it); default the language of the header it has now. */
  language?: string
  values?: string[]
}
export interface AssetEditRequest {
  assets: AssetEdit[]
  /** Replace the assets in this one campaign only (a new asset there, the old one unlinked there) instead of editing them. */
  onlyInCampaignId?: string
}
export interface AssetEditLiveState { assets: LiveEditAsset[]; links: LiveAssetLink[] }

/** An asset's content as Nexus edits it: the fields of its type. In a record, only the fields the change wrote. */
export interface AssetContent {
  assetId: string
  type: AssetFieldType
  linkText?: string | null
  description1?: string | null
  description2?: string | null
  finalUrl?: string | null
  calloutText?: string | null
  header?: string | null
  /** With a header: its language, so the header can be named again (undo). */
  language?: string | null
  values?: string[]
}
export interface AssetEditRecord { mode: 'edit'; assets: AssetContent[] }
export interface AssetReplacement { oldAssetId: string; newAssetId: string; fieldType: AssetFieldType; status: AssetLinkStatus; text: string }
export interface AssetReplaceRecord { mode: 'replace'; campaignId: string; replaced: AssetReplacement[] }
export interface AssetReplaceBefore { mode: 'replace'; campaignId: string; links: Array<{ assetId: string; fieldType: AssetFieldType; status: AssetLinkStatus; text: string }> }

export const MAX_EDIT_ASSETS = 20
const OP = 'op:'
const KIND: Record<AssetFieldType, string> = { SITELINK: 'sitelink', CALLOUT: 'callout', STRUCTURED_SNIPPET: 'structured snippet' }
const FIELDS_OF: Record<AssetFieldType, ReadonlyArray<keyof AssetEdit>> = {
  SITELINK: ['linkText', 'description1', 'description2', 'finalUrl'],
  CALLOUT: ['calloutText'],
  STRUCTURED_SNIPPET: ['header', 'language', 'values'],
}
const EDIT_FIELDS: ReadonlyArray<keyof AssetEdit> = ['linkText', 'description1', 'description2', 'finalUrl', 'calloutText', 'header', 'language', 'values']
const MASK: Record<string, string> = {
  linkText: 'sitelink_asset.link_text', description1: 'sitelink_asset.description1', description2: 'sitelink_asset.description2',
  finalUrl: 'final_urls', calloutText: 'callout_asset.callout_text', header: 'structured_snippet_asset.header', values: 'structured_snippet_asset.values',
}
const WORD: Record<string, string> = { linkText: 'link text', description1: 'description 1', description2: 'description 2', finalUrl: 'final URL', calloutText: 'text', header: 'header', values: 'values' }
const isFieldType = (v: unknown): v is AssetFieldType => ASSET_FIELD_TYPES.includes(v as AssetFieldType)
const blank = (s: string | null | undefined) => (s ?? '').trim() || null

/** The first language whose header list holds this exact header (Google's own string), or null. */
export function snippetLanguageOf(header: string | null | undefined): string | null {
  if (!header) return null
  return SNIPPET_LANGUAGES.find((l) => snippetHeaders(l)?.headers.includes(header)) ?? null
}

/** An asset as it is now, with every field of its type. */
export function assetNow(asset: LiveEditAsset): AssetContent | null {
  if (!isFieldType(asset.type)) return null
  switch (asset.type) {
    case 'SITELINK': return { assetId: asset.assetId, type: asset.type, linkText: asset.linkText ?? null, description1: asset.description1 ?? null, description2: asset.description2 ?? null, finalUrl: asset.finalUrls[0] ?? null }
    case 'CALLOUT': return { assetId: asset.assetId, type: asset.type, calloutText: asset.calloutText ?? null }
    case 'STRUCTURED_SNIPPET': return { assetId: asset.assetId, type: asset.type, header: asset.header ?? null, language: snippetLanguageOf(asset.header), values: asset.values ?? [] }
  }
}

/** What an asset reads as, to a person. */
export function assetLabel(c: AssetContent): string {
  if (c.type === 'STRUCTURED_SNIPPET') return `${c.header ?? ''}: ${(c.values ?? []).join(', ')}`
  return (c.type === 'SITELINK' ? c.linkText : c.calloutText) ?? ''
}

const placeOf = (l: LiveAssetLink) => (l.level === 'account' ? 'the account' : l.level === 'campaign' ? `campaign "${l.campaignName}"` : `ad group "${l.adGroupName}" (${l.campaignName})`)

export function assetEditDraft(customer: string, request: AssetEditRequest, live: AssetEditLiveState): GoogleChangeDraft | { refusal: string } {
  const edits = request.assets ?? []
  if (!edits.length) return { refusal: 'Name at least one asset to change (assets).' }
  if (edits.length > MAX_EDIT_ASSETS) return { refusal: `At most ${MAX_EDIT_ASSETS} assets in one request (${edits.length} asked).` }
  const replaceIn = request.onlyInCampaignId ?? null
  const byId = new Map(live.assets.map((a) => [a.assetId, a]))
  const seen = new Set<string>()
  const problems: string[] = []
  const tagNotes: string[] = []
  const planned: Array<{ asset: LiveEditAsset; now: AssetContent; next: AssetContent; changed: string[]; link: LiveAssetLink | null }> = []

  // 1. what each asset becomes; Google's rules checked on it whole, every problem at once
  for (const edit of edits) {
    if (seen.has(edit.assetId)) return { refusal: `Asset ${edit.assetId} is named twice.` }
    seen.add(edit.assetId)
    const asset = byId.get(edit.assetId)
    if (!asset) return { refusal: `Asset ${edit.assetId} is not in this account. google-ads-live view assets lists them.` }
    const now = assetNow(asset)
    if (!now) return { refusal: `Asset ${edit.assetId} is a ${asset.type ?? 'asset of unknown type'}: Nexus changes sitelinks, callouts and structured snippets.` }
    const asked = EDIT_FIELDS.filter((f) => edit[f] !== undefined)
    const wrong = asked.filter((f) => !FIELDS_OF[now.type].includes(f))
    if (wrong.length) return { refusal: `Asset ${edit.assetId} is a ${KIND[now.type]}: ${wrong.join(', ')} ${wrong.length === 1 ? 'is not one of its fields' : 'are not its fields'} (${FIELDS_OF[now.type].join(', ')}).` }
    if (!asked.filter((f) => f !== 'language').length) return { refusal: `Asset ${edit.assetId}: say what changes (${FIELDS_OF[now.type].filter((f) => f !== 'language').join(', ')}).` }
    if (!replaceIn && asset.source === 'AUTOMATICALLY_CREATED') {
      return { refusal: `Asset ${edit.assetId} ("${assetLabel(now)}") was made by Google (automatically created): Google does not let it be changed. Ask with onlyInCampaignId to replace it in a campaign with an asset of your own.` }
    }
    let link: LiveAssetLink | null = null
    if (replaceIn) {
      link = live.links.find((l) => l.assetId === asset.assetId && l.level === 'campaign' && l.campaignId === replaceIn && l.fieldType === now.type) ?? null
      if (!link) return { refusal: `Asset ${edit.assetId} ("${assetLabel(now)}") is not linked to campaign ${replaceIn} as a ${KIND[now.type]}: there is nothing to replace there (google-ads-live view assets lists a campaign's assets).` }
    }
    const where = `asset ${edit.assetId}`
    const next: AssetContent = { ...now }
    if (now.type === 'SITELINK') {
      if (edit.linkText !== undefined) next.linkText = edit.linkText.trim()
      if (edit.description1 !== undefined) next.description1 = blank(edit.description1)
      if (edit.description2 !== undefined) next.description2 = blank(edit.description2)
      if (edit.finalUrl !== undefined) next.finalUrl = edit.finalUrl.trim()
      const p = widthProblem(`${where}, link text`, next.linkText, ASSET_LIMITS.linkText)
      if (p) problems.push(p)
      if (!!next.description1 !== !!next.description2) problems.push(`${where}: a sitelink has both description lines or neither (Google's rule)`)
      for (const d of ['description1', 'description2'] as const) {
        if (next[d]) { const q = widthProblem(`${where}, ${WORD[d]}`, next[d], ASSET_LIMITS.sitelinkDescription); if (q) problems.push(q) }
      }
      if (edit.finalUrl !== undefined || (replaceIn && !next.finalUrl)) { const q = httpsUrlProblem(where, next.finalUrl); if (q) problems.push(q) }
      for (const f of ['linkText', 'description1', 'description2'] as const) { const t = tagWarning(`${where}, ${WORD[f]}`, next[f]); if (t) tagNotes.push(t) }
    } else if (now.type === 'CALLOUT') {
      next.calloutText = edit.calloutText!.trim()
      const p = widthProblem(where, next.calloutText, ASSET_LIMITS.callout)
      if (p) problems.push(p)
      const t = tagWarning(where, next.calloutText)
      if (t) tagNotes.push(t)
    } else {
      if (edit.header !== undefined) {
        const language = edit.language?.trim() || now.language || 'en'
        const header = snippetHeader(edit.header, language)
        if ('problem' in header) problems.push(`${where}: ${header.problem}`)
        else { next.header = header.header; next.language = snippetLanguageOf(header.header) ?? language }
      }
      if (edit.values !== undefined) {
        next.values = edit.values.map((v) => v.trim())
        const L = ASSET_LIMITS
        if (next.values.length < L.minSnippetValues || next.values.length > L.maxSnippetValues) problems.push(`${where}: ${plural(next.values.length, 'value')} (Google needs ${L.minSnippetValues} to ${L.maxSnippetValues})`)
        const valueSeen = new Map<string, number>()
        next.values.forEach((v, j) => {
          const p = widthProblem(`${where}, value ${j + 1}`, v, L.snippetValue)
          if (p) { problems.push(p); return }
          const first = valueSeen.get(textKey(v))
          if (first !== undefined) problems.push(`${where}, value ${j + 1} "${v}" repeats value ${first + 1} exactly (Google's policy refuses a repeated value)`)
          else valueSeen.set(textKey(v), j)
          const t = tagWarning(`${where}, value ${j + 1}`, v)
          if (t) tagNotes.push(t)
        })
      }
    }
    const changed = (['linkText', 'description1', 'description2', 'finalUrl', 'calloutText', 'header', 'values'] as const)
      .filter((f) => f in next && JSON.stringify(next[f] ?? null) !== JSON.stringify(now[f] ?? null))
    planned.push({ asset, now, next, changed, link })
  }
  if (problems.length) return { refusal: `Not queued — the assets break Google's rules (nothing was sent): ${problems.join('; ')}.` }
  const skipped = planned.filter((p) => !p.changed.length).map((p) => `Asset ${p.asset.assetId} ("${assetLabel(p.now)}") already reads so.`)
  const work = planned.filter((p) => p.changed.length)
  if (!work.length) return { refusal: `Nothing to change: ${skipped.join(' ')}` }

  const operations: GoogleMutateOperation[] = []
  const lines: Array<[string, unknown, unknown]> = []
  const warnings: string[] = []
  const stands = {
    assets: work.map((p) => ({ ...p.now, source: p.asset.source, finalMobileUrls: p.asset.finalMobileUrls, urls: p.asset.urls })),
    links: live.links.filter((l) => work.some((p) => p.asset.assetId === l.assetId)).map((l) => `${l.assetId}~${l.level}~${l.campaignId ?? ''}~${l.adGroupId ?? ''}~${l.fieldType}~${l.status}`),
  }

  // 2a. replace in one campaign: new assets, their links, the old links taken off
  if (replaceIn) {
    const campaignName = work[0].link!.campaignName ?? replaceIn
    const campaignRes = `${customer}/campaigns/${replaceIn}`
    const record: AssetReplaceRecord = { mode: 'replace', campaignId: replaceIn, replaced: [] }
    const before: AssetReplaceBefore = { mode: 'replace', campaignId: replaceIn, links: [] }
    const linkOps: GoogleMutateOperation[] = []
    const unlinkOps: GoogleMutateOperation[] = []
    let temp = -1
    for (const p of work) {
      const resourceName = `${customer}/assets/${temp--}`
      const n = p.next
      // The old asset's tracking goes with the new one (sales tracking may rest on it).
      const tracking = {
        ...(p.asset.urls.trackingTemplate ? { trackingUrlTemplate: p.asset.urls.trackingTemplate } : {}),
        ...(p.asset.urls.finalUrlSuffix ? { finalUrlSuffix: p.asset.urls.finalUrlSuffix } : {}),
        ...(p.asset.urls.customParameters.length ? { urlCustomParameters: p.asset.urls.customParameters } : {}),
      }
      const body: Record<string, unknown> = n.type === 'SITELINK'
        ? { finalUrls: [n.finalUrl], ...(p.asset.finalMobileUrls.length ? { finalMobileUrls: p.asset.finalMobileUrls } : {}), sitelinkAsset: { linkText: n.linkText, ...(n.description1 && n.description2 ? { description1: n.description1, description2: n.description2 } : {}) } }
        : n.type === 'CALLOUT' ? { calloutAsset: { calloutText: n.calloutText } }
          : { structuredSnippetAsset: { header: n.header, values: n.values } }
      operations.push({ assetOperation: { create: { resourceName, ...tracking, ...body } } })
      const status: AssetLinkStatus = p.link!.status === 'PAUSED' ? 'PAUSED' : 'ENABLED'
      linkOps.push({ campaignAssetOperation: { create: { campaign: campaignRes, asset: resourceName, fieldType: n.type, ...(status === 'PAUSED' ? { status } : {}) } } })
      unlinkOps.push({ campaignAssetOperation: { remove: `${customer}/campaignAssets/${replaceIn}~${p.asset.assetId}~${n.type}` } })
      record.replaced.push({ oldAssetId: p.asset.assetId, newAssetId: `${OP}${operations.length - 1}`, fieldType: n.type, status, text: assetLabel(n) })
      before.links.push({ assetId: p.asset.assetId, fieldType: n.type, status, text: assetLabel(p.now) })
      lines.push([`${KIND[n.type]} "${assetLabel(p.now)}" (asset ${p.asset.assetId}) in "${campaignName}"`, `linked${status === 'PAUSED' ? ', paused' : ''}`, `unlinked; a new ${KIND[n.type]} "${assetLabel(n)}" linked${status === 'PAUSED' ? ', paused' : ''}${n.type === 'SITELINK' ? ` — ${n.finalUrl}` : ''}`])
      if (p.asset.source === 'AUTOMATICALLY_CREATED') warnings.push(`Asset ${p.asset.assetId} was made by Google: it cannot be changed, so it is replaced in "${campaignName}".`)
    }
    operations.push(...linkOps, ...unlinkOps)
    warnings.unshift(`In "${campaignName}" each asset is replaced by a new one with the edited text (linked with the old link's status; its URLs and tracking copied) and the old one is unlinked there, in this one request. The old asset keeps its numbers and stays in the account and wherever else it is linked; the new one starts from nothing and Google reviews it. A start or end date or a schedule the old asset has is not copied.`)
    warnings.push(...tagNotes)
    const { changes, more } = changeLines(lines)
    return {
      summary: `Google Ads assets of campaign "${campaignName}": replace ${plural(work.length, 'asset')} with new ones (the old ones unlinked there, kept elsewhere).`,
      changes,
      totals: { operations: operations.length, assetsReplaced: work.length, ...(more ? { linesNotShown: more } : {}) },
      warnings,
      spendsMoney: [],
      skipped,
      operations,
      stands,
      before,
      after: record,
    }
  }

  // 2b. edit in place
  const before: AssetEditRecord = { mode: 'edit', assets: [] }
  const after: AssetEditRecord = { mode: 'edit', assets: [] }
  for (const p of work) {
    const n = p.next
    const update: Record<string, unknown> = { resourceName: `${customer}/assets/${p.asset.assetId}` }
    const inner: Record<string, unknown> = {}
    const was: AssetContent = { assetId: p.asset.assetId, type: n.type }
    const is: AssetContent = { assetId: p.asset.assetId, type: n.type }
    const label = `${KIND[n.type]} "${assetLabel(p.now)}" (asset ${p.asset.assetId})`
    for (const f of p.changed) {
      const to = n[f]
      if (f === 'finalUrl') update.finalUrls = [to]
      // Google's JSON names the inner fields as Nexus does (sitelinkAsset.linkText, calloutAsset.calloutText, …).
      else if (to !== null && to !== undefined) inner[f] = to
      Object.assign(was, { [f]: p.now[f] ?? null })
      Object.assign(is, { [f]: to ?? null })
      if (f === 'header') { was.language = p.now.language ?? null; is.language = n.language ?? null }
      lines.push([`${label} ${WORD[f]}`, f === 'values' ? (p.now.values ?? []).join(', ') : p.now[f] ?? '(none)', f === 'values' ? (n.values ?? []).join(', ') : to ?? '(none)'])
    }
    const innerKey = n.type === 'SITELINK' ? 'sitelinkAsset' : n.type === 'CALLOUT' ? 'calloutAsset' : 'structuredSnippetAsset'
    if (p.changed.some((f) => f !== 'finalUrl')) update[innerKey] = inner
    operations.push({ assetOperation: { update, updateMask: p.changed.map((f) => MASK[f]).join(',') } })
    before.assets.push(was)
    after.assets.push(is)
    const places = live.links.filter((l) => l.assetId === p.asset.assetId)
    if (!places.length) warnings.push(`Asset ${p.asset.assetId} ("${assetLabel(p.now)}") is linked nowhere: the edit shows nowhere until it is linked.`)
    else if (places.length === 1) warnings.push(`Asset ${p.asset.assetId} ("${assetLabel(p.now)}") is linked in one place — ${placeOf(places[0])}: the edit changes it there.`)
    else {
      warnings.push(`Asset ${p.asset.assetId} ("${assetLabel(p.now)}") is linked in ${plural(places.length, 'place')} — ${places.slice(0, 8).map(placeOf).join(', ')}${places.length > 8 ? ' …' : ''}: the edit changes it in all of them. To change it in one campaign only, ask with onlyInCampaignId.`)
    }
  }
  warnings.unshift(`Each asset keeps its id, so its numbers stay with it. Google reviews ${work.length === 1 ? 'the changed asset' : `the ${work.length} changed assets`} again: google-ads-live view assets shows the review.`)
  warnings.push(...tagNotes)
  const { changes, more } = changeLines(lines)
  const kinds = [...new Set(work.map((p) => KIND[p.next.type]))]
  return {
    summary: `Google Ads assets: edit ${plural(work.length, 'asset')} in place (${kinds.join(', ')}); each keeps its id and numbers, everywhere it is linked.`,
    changes,
    totals: { operations: operations.length, assetsEdited: work.length, ...(more ? { linesNotShown: more } : {}) },
    warnings,
    spendsMoney: [],
    skipped,
    operations,
    stands,
    before,
    after,
  }
}

/** The record of a run: each new asset (replace) gets the id Google gave it (`assetResult` of the operation that made it). */
export function assetEditRecordAfterRun(after: AssetEditRecord | AssetReplaceRecord, responses: GoogleMutateResponse[]): AssetEditRecord | AssetReplaceRecord {
  if (after.mode === 'edit') return { mode: 'edit', assets: after.assets.map((a) => ({ ...a })) }
  const idAt = (index: number): string | null => {
    const name = responses[index]?.assetResult?.resourceName
    return name ? name.slice(name.lastIndexOf('/') + 1) : null
  }
  return { ...after, replaced: after.replaced.map((r) => ({ ...r, newAssetId: r.newAssetId.startsWith(OP) ? idAt(Number(r.newAssetId.slice(OP.length))) ?? r.newAssetId : r.newAssetId })) }
}
